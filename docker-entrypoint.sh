#!/bin/sh
# Каталог состояния приезжает снаружи и может принадлежать кому угодно: bind-mount на
# Linux создаётся от root, том — унаследует владельца из образа только если создаётся
# впервые и не пуст. Полагаться на это нельзя: бот уже дважды падал на новом сервере с
# «unable to open database file».
#
# Поэтому: если стартовали от root — выравниваем владельца и роняем привилегии.
# Сам бот всегда работает под fsbot, root живёт ровно до exec.
set -e

STATE_DIR="${FSBOT_STATE_DIR:-/data}"

if [ "$(id -u)" = "0" ]; then
    mkdir -p "$STATE_DIR"
    chown -R fsbot:fsbot "$STATE_DIR"
    exec su-exec fsbot "$@"
fi

# Уже не root (например, docker run --user) — проверяем, что писать сможем, и говорим
# понятным языком, если нет. Иначе ошибка всплывёт стеком из недр sqlite.
if [ ! -w "$STATE_DIR" ]; then
    echo "Каталог состояния $STATE_DIR недоступен на запись пользователю $(id -un) (uid $(id -u))." >&2
    echo "Владелец каталога: $(ls -ldn "$STATE_DIR" 2>/dev/null || echo 'каталога нет')" >&2
    echo "Запусти контейнер без --user, чтобы entrypoint выставил владельца сам." >&2
    exit 1
fi

exec "$@"
